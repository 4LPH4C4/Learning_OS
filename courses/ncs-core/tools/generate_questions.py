def pick(items: list[str], r: int, s: int, salt: int = 0) -> str:
    return items[(r * 3 + s * 5 + salt) % len(items)]


def question(
    r: int, s: int, skill: str, lesson: str, case: int, topic: str,
    prompt: str, correct: str, wrongs: list[str], explanation: str, difficulty: int,
) -> dict:
    projects = ("해오름", "푸른길", "새물결", "한마음", "다온", "나래", "온누리", "이음", "가온", "마루")
    units = ("동부", "서부", "남부", "북부", "중앙", "해안", "산단", "도심")
    prompt = f"{projects[r - 1]} 프로젝트 {units[s]} 거점의 상황이다. {prompt}"
    if skill != "numeracy":
        suffixes = (
            " — 이 판단을 실행 원칙으로 정한다.",
            " — 이 판단을 해당 거점의 실행 원칙으로 정한다.",
            " — 이 판단을 이번 업무의 공식 실행 원칙으로 정한다.",
            " — 이 판단을 관련 부서가 따를 이번 업무의 실행 원칙으로 정한다.",
            " — 이 판단을 관련 부서와 협력사가 함께 따를 이번 분기 실행 원칙으로 정한다.",
            " — 이 판단을 관련 부서와 외부 협력사가 함께 따를 이번 분기의 공식 실행 원칙으로 정한다.",
        )
        raw_choices = [correct, *wrongs]
        target_length = max(map(len, raw_choices)) + len(suffixes[0])
        balanced: list[str] = []
        for index, text in enumerate(raw_choices):
            # 선택 내용의 뜻은 유지하면서, 모두 실제 운영 원칙으로 채택한다는 같은 맥락을 붙인다.
            # 목표 길이에 가장 가까운 표현을 고르되 정답에만 긴 설명이 붙는 패턴은 만들지 않는다.
            preferred = target_length + ((index + r + s) % 3 - 1)
            suffix = min(suffixes, key=lambda item: abs(len(text) + len(item) - preferred))
            balanced.append(text + suffix)
        correct, wrongs = balanced[0], balanced[1:]

    seed = int(hashlib.sha256(f"{r}:{skill}:{s}:{case}".encode()).hexdigest()[:12], 16)
    shuffled_wrongs = list(wrongs)
    random.Random(seed).shuffle(shuffled_wrongs)
    offsets = {
        "communication": 0,
        "numeracy": 8,
        "problem-solving": 15,
        "self-management": 22,
        "interpersonal": 29,
        "digital": 36,
        "work-ethics": 43,
    }
    answer_index = (offsets[skill] + s + r) % 4
    choice_texts = shuffled_wrongs[:]
    choice_texts.insert(answer_index, correct)
    choices = [(text, index == answer_index) for index, text in enumerate(choice_texts)]
    ids = ("a", "b", "c", "d")
    options = [{"id": oid, "text": text} for oid, (text, _) in zip(ids, choices)]
    answer = next(oid for oid, (_, ok) in zip(ids, choices) if ok)
    incorrect = {
        oid: f"이 선택지는 핵심 조건을 충족하지 않는다. {explanation}"
        for oid, (_, ok) in zip(ids, choices) if not ok
    }
    return {
        "id": f"ncs-r{r:02d}-{skill}-{s + 1:02d}-{case + 1:02d}",
        "lesson_id": lesson,
        "skill_id": skill,
        "topic": topic,
        "difficulty": difficulty,
        "type": "single_choice",
        "sets": [f"round-{r:02d}"],
        "prompt": prompt,
        "options": options,
        "correct_answers": [answer],
        "explanation": explanation,
        "incorrect_explanations": incorrect,
        "source_ref": SOURCE,
    }


