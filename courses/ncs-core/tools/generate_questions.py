BUILDERS: dict[str, Callable[[int, int, str], dict]] = {
    "communication": communication,
    "numeracy": numeracy,
    "problem-solving": problem_solving,
    "self-management": self_management,
    "interpersonal": interpersonal,
    "digital": digital,
    "work-ethics": work_ethics,
}


def build_all() -> list[dict]:
    return [
        BUILDERS[skill](round_no, slot, lesson)
        for round_no in range(1, 11)
        for skill, lesson, count in SKILLS
        for slot in range(count)
    ]


def validate(questions: list[dict]) -> None:
    assert len(questions) == 500
    ids = [item["id"] for item in questions]
    assert len(ids) == len(set(ids))
    prompts = [item["prompt"] for item in questions]
    assert len(prompts) == len(set(prompts)), "완전히 같은 prompt가 있다"
    for round_no in range(1, 11):
        set_id = f"round-{round_no:02d}"
        selected = [item for item in questions if item["sets"] == [set_id]]
        assert len(selected) == 50
        counts = {skill: sum(item["skill_id"] == skill for item in selected) for skill, _, _ in SKILLS}
        assert counts["communication"] == 8
        assert all(counts[skill] == 7 for skill, _, _ in SKILLS if skill != "communication")
        positions = {
            option_id: sum(item["correct_answers"] == [option_id] for item in selected)
            for option_id in ("a", "b", "c", "d")
        }
        assert max(positions.values()) - min(positions.values()) <= 6
        assert sum(item["difficulty"] >= 4 for item in selected) >= 5
    correct_lengths: list[int] = []
    wrong_lengths: list[int] = []
    longest_correct = 0
    for item in questions:
        option_ids = {option["id"] for option in item["options"]}
        answers = set(item["correct_answers"])
        assert len(option_ids) == 4 and answers <= option_ids
        assert len({option["text"] for option in item["options"]}) == 4
        assert set(item["incorrect_explanations"]) == option_ids - answers
        assert item["source_ref"].startswith("https://www.ncs.go.kr/")
        lengths = {option["id"]: len(option["text"]) for option in item["options"]}
        correct_id = item["correct_answers"][0]
        correct_lengths.append(lengths[correct_id])
        wrong_lengths.extend(length for oid, length in lengths.items() if oid != correct_id)
        longest_correct += lengths[correct_id] >= max(lengths.values())
    assert longest_correct / len(questions) <= 0.40
    assert abs(sum(correct_lengths) / len(correct_lengths) - sum(wrong_lengths) / len(wrong_lengths)) <= 5


def main() -> None:
    questions = build_all()
    validate(questions)
    payload = {"schema_version": 1, "course_id": "ncs-core", "questions": questions}
    output = ROOT / "questions.yaml"
    output.write_text(yaml.safe_dump(payload, allow_unicode=True, sort_keys=False, width=120), encoding="utf-8")
    loaded = yaml.safe_load(output.read_text(encoding="utf-8"))
    validate(loaded["questions"])
    print(f"generated {len(questions)} questions -> {output}")


if __name__ == "__main__":
    main()
